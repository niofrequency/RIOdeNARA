(function(){
  function getLang(){
    var stored;
    try{ stored = localStorage.getItem('rdn_lang'); }catch(e){ stored = null; }
    return stored === 'id' ? 'id' : 'en';
  }

  function apply(lang){
    var dict = window.RDN_I18N[lang] || window.RDN_I18N.en;
    document.documentElement.setAttribute('lang', lang === 'id' ? 'id' : 'en');

    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if(dict[key] !== undefined){ el.textContent = dict[key]; }
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(function(el){
      el.getAttribute('data-i18n-attr').split('|').forEach(function(pair){
        var parts = pair.split(':');
        var attr = parts[0], key = parts[1];
        if(key && dict[key] !== undefined){ el.setAttribute(attr, dict[key]); }
      });
    });

    document.querySelectorAll('.lang-btn').forEach(function(btn){
      var active = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', active);
      btn.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    document.dispatchEvent(new CustomEvent('rdn:langchange', { detail: { lang: lang, dict: dict } }));
  }

  function setLang(lang){
    lang = lang === 'id' ? 'id' : 'en';
    try{ localStorage.setItem('rdn_lang', lang); }catch(e){}
    apply(lang);
  }

  document.addEventListener('DOMContentLoaded', function(){
    apply(getLang());
    document.querySelectorAll('.lang-btn').forEach(function(btn){
      btn.addEventListener('click', function(){ setLang(btn.getAttribute('data-lang')); });
    });
  });

  window.RDN_setLang = setLang;
  window.RDN_getLang = getLang;
  window.RDN_applyLang = apply;
  window.RDN_t = function(key){
    var dict = window.RDN_I18N[getLang()] || window.RDN_I18N.en;
    return dict[key] !== undefined ? dict[key] : key;
  };
})();
